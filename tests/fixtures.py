def make_eml_with_attachment(path: Path, attachment: Path) -> Path:
    message = EmailMessage()
    message["From"] = "a@example.com"
    message["To"] = "b@example.com"
    message["Subject"] = "Please review"
    message.set_content("See the attached note.")
    message.add_attachment(
        attachment.read_bytes(),
        maintype="text",
        subtype="plain",
        filename=attachment.name,
    )
    path.write_bytes(message.as_bytes())
    return path


def make_zip(path: Path, files: dict[str, Path]) -> Path:
    with zipfile.ZipFile(path, "w") as archive:
        for name, file_path in files.items():
            archive.write(file_path, arcname=name)
    return path
